package com.scivicslab.turingworkflow.plugins.rstframe;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.concurrent.Future;
import java.util.concurrent.atomic.AtomicInteger;
import java.util.function.Consumer;
import java.util.function.Function;

/**
 * Turns book sections into rst-on-lisp rule files by asking a writer to identify sentence relations and OCR
 * misreadings.
 *
 * <ul><li>{@code converter(book, node, section)} returns a converter for a single section that is ready to be
 * queried.</li><li>{@code tag(book, node, section, writer)} returns a rule file for the specified section after asking
 * the writer every question required to build it.</li><li>{@code tagAll(store, book, only, writer, parallel, log)}
 * returns a summary string of how many sections were successfully made and how many failed, processing the requested
 * sections in parallel.</li></ul>
 *
 * One instance may serve several workflows or threads at once.
 */
public final class SectionTagging {

    private SectionTagging() {
    }

    /**
     * Creates a converter for a specific section of a book, which is used to ask a writer questions about that
     * section's text and relations.
     *
     * @param book the name of the book
     * @param node the node in the book's outline representing the section's position and heading
     * @param section the section's actual text and content
     * @return a {@link BookFileToRules} instance that can be used to iterate through and answer questions about the
     * section
     */
    public static BookFileToRules converter(String book, BookOutline.Node node, BookSections.Section section) {
        String text = "## " + node.number() + ". " + node.title() + "\n\n" + section.text() + "\n";
        String id = ("Book_" + book + "_" + node.number()).replaceAll("[^A-Za-z0-9]+", "_");
        return new BookFileToRules(text, "h2:" + book + "/" + node.number(), id);
    }

    /**
     * Asks a writer every question for a specific section and returns the resulting rst-on-lisp rule file.
     *
     * <p>Returns a {@code BookStore.SectionRules} containing the section's number, the rule file, the code files, and
     * the number of questions asked.
     *
     * <p>The {@code writer} function is called for every question generated by the section's converter; the result of
     * each call is used as the answer to that question.
     *
     * @param book the name of the book
     * @param node the node in the book's outline representing the section's position
     * @param section the section's text and data
     * @param writer a function that takes a question string and returns an answer string
     * @return a {@code BookStore.SectionRules} object holding the section's number, the generated rule file, the code
     * files, and the count of questions asked
     */
    public static BookStore.SectionRules tag(String book, BookOutline.Node node, BookSections.Section section, Function<String, String> writer) {
        BookFileToRules c = converter(book, node, section);
        String q;
        while ((q = c.nextQuestion()) != null) c.answer(writer.apply(q));
        return new BookStore.SectionRules(node.number(), c.ruleFile(), c.codeFiles(), c.asked());
    }

    /**
     * Generates rst-on-lisp rule files for sections of a book and stores them in the {@code BookStore}, either for all
     * sections currently lacking rule files or for a specific subset.
     *
     * <ul>
     * <li>If {@code only} is empty, it processes every section in {@code book} that does not already have a rule file
     * in the store.</li>
     * <li>If {@code only} is not empty, it processes only the sections whose numbers are listed in {@code only}.</li>
     * <li>The {@code parallel} argument specifies the number of sections to process at a time.</li>
     * <li>The {@code writer} function is called for every question required to build a section's rule file.</li>
     * <li>The {@code log} consumer receives progress messages and failure reports.</li>
     * </ul>
     *
     * <p>Returns a string stating how many sections were successfully made into rule files and how many failed.</p>
     *
     * <p>A section that fails during processing is reported via {@code log} and is not stored; a subsequent call to
     * {@code tagAll} will attempt to process it again.</p>
     *
     * <pre>{@code
     * tagAll(store, "core-java-14-vol1", List.of("1.2.5"), writer, 4, System.out::println)
     * }</pre>
     *
     * @param store the database containing the book's outline, sections, and existing rule files
     * @param book the name of the book to process
     * @param only a list of specific section numbers to process; if empty, all sections without rule files are
     * processed
     *
     * @param writer a function that takes a question string and returns an answer string
     * @param parallel the maximum number of sections to process simultaneously
     * @param log a consumer for progress and error messages
     * @return a string in the form "X section(s) of [book] made into rule files, Y failed"
     * @throws Exception if an error occurs during the orchestration of the tasks
     */
    public static String tagAll(BookStore store, String book, List<String> only, Function<String, String> writer, int parallel,
            Consumer<String> log) throws Exception {
        Map<String, BookOutline.Node> nodes = new java.util.LinkedHashMap<>();
        for (BookOutline.Node n : store.outline(book)) nodes.put(n.number(), n);
        java.util.Set<String> done = store.sectionsWithRules(book);
        List<BookSections.Section> todo = new ArrayList<>();
        for (BookSections.Section s : store.sections(book)) {
            if (only.isEmpty() ? !done.contains(s.number()) : only.contains(s.number())) todo.add(s);
        }
        log.accept("start: " + todo.size() + " section(s) of " + book + ", " + parallel + " at a time");
        AtomicInteger made = new AtomicInteger();
        AtomicInteger failed = new AtomicInteger();
        BatchFailures failures = new BatchFailures();
        LimitedVirtualThreads threads = new LimitedVirtualThreads(parallel);
        try {
            List<Future<?>> fs = new ArrayList<>();
            for (BookSections.Section s : todo) {
                fs.add(threads.submit(() -> {
                    long t0 = System.currentTimeMillis();
                    try {
                        BookStore.SectionRules r = tag(book, nodes.get(s.number()), s, writer);
                        store.saveSectionRules(book, r);
                        log.accept("done " + made.incrementAndGet() + "/" + todo.size() + " " + s.number() + " (" + r.questions() + " questions, "
                                + (System.currentTimeMillis() - t0) / 1000 + "s)");
                    } catch (Exception e) {
                        failed.incrementAndGet();
                        log.accept("FAILED " + s.number() + ": " + e.getMessage());
                        failures.add(s.number(), e);
                    }
                }));
            }
            for (Future<?> f : fs) f.get();
        } finally {
            threads.shutdown();
        }
        return failures.outcome(todo.size(), made.get() + " section(s) of " + book + " made into rule files, " + failed.get() + " failed");
    }
}

package com.scivicslab.turingworkflow.plugins.report.sections.basic;

import com.scivicslab.turingworkflow.plugins.report.SectionBuilder;

/**
 * Generates a section for a report that displays the name of a workflow.
 *
 * <p>The section consists of a header and the name itself. If the workflow name is not explicitly provided, it uses
 * the filename from the workflow path, or {@code (unknown)} if no path is available.</p>
 *
 * <ul>
 * <li>{@link #generate()} returns a string containing the header {@code [Workflow Name]} followed by the name on a new
 * line.</li>
 * <li>{@link #getTitle()} always returns {@code null} because the header is part of the generated content.</li>
 * </ul>
 *
 * <p>One instance may serve several workflows if the name and path are updated between calls.</p>
 *
 * <pre>{@code
 * WorkflowNameSection section = new WorkflowNameSection();
 * section.setWorkflowName("deploy-all");
 * section.generate(); // returns "[Workflow Name]\ndeploy-all\n"
 * }</pre>
 *
 * @author devteam@scivicslab.com
 * @since 2.16.0
 */
public class WorkflowNameSection implements SectionBuilder {

    private String workflowName;
    private String workflowPath;

    /**
     * Sets the workflow name to be used in the generated report.
     *
     * @param name the name of the workflow extracted from the YAML file
     */
    public void setWorkflowName(String name) {
        this.workflowName = name;
    }

    /**
     * Sets the workflow file path to be used as a fallback for the workflow name if the name is not explicitly
     * provided.
     *
     * @param path the workflow file path
     */
    public void setWorkflowPath(String path) {
        this.workflowPath = path;
    }

    /**
     * Returns a string containing a {@code [Workflow Name]} block.
     *
     * <p>The result is the workflow name itself, preceded by the header {@code [Workflow Name]} and followed by a
     * newline. If no name was provided via {@link #setWorkflowName(String)}, the content is the filename extracted
     * from the path provided to {@link #setWorkflowPath(String)}. If neither a name nor a path is available, the
     * result is {@code [Workflow Name]\n(unknown)\n}.</p>
     */
    @Override
    public String generate() {
        String name = workflowName;
        if (name == null || name.isEmpty()) {
            // Fall back to file name
            if (workflowPath != null && !workflowPath.isEmpty()) {
                int lastSlash = workflowPath.lastIndexOf('/');
                name = lastSlash >= 0 ? workflowPath.substring(lastSlash + 1) : workflowPath;
            } else {
                name = "(unknown)";
            }
        }
        return "[Workflow Name]\n" + name + "\n";
    }

    /**
     * Returns {@code null}.
     *
     * <p>The title is embedded within the content generated by {@link #generate()}.</p>
     */
    @Override
    public String getTitle() {
        return null;  // Title is embedded in content
    }
}

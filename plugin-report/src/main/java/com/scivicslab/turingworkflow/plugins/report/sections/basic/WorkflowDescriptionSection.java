package com.scivicslab.turingworkflow.plugins.report.sections.basic;

import com.scivicslab.turingworkflow.plugins.report.SectionBuilder;

/**
 * Generates a report section containing the workflow's description.
 *
 * <ul><li>{@link #generate()} returns a string formatted as a {@code [Description]} block with each line of the
 * description indented by two spaces, or an empty string if no description is set.</li><li>{@link #getTitle()} returns
 * {@code null} because the title is embedded within the generated content.</li></ul>
 *
 * <p>A caller must call {@link #setDescription(String)} before {@link #generate()} to ensure the section is not
 * empty.</p>
 *
 * <pre>{@code
 * WorkflowDescriptionSection section = new WorkflowDescriptionSection();
 * section.setDescription("Deploy all nodes");
 * String content = section.generate();
 * // content is "[Description]\n  Deploy all nodes\n"
 * }</pre>
 *
 * @author devteam@scivicslab.com
 * @since 2.16.0
 */
public class WorkflowDescriptionSection implements SectionBuilder {

    private String description;

    /**
     * Sets the workflow description to be included in the report.
     *
     * @param description the workflow description from YAML
     */
    public void setDescription(String description) {
        this.description = description;
    }

    /**
     * Returns a string containing a {@code [Description]} block where each line of the description is indented by two
     * spaces.
     *
     * If the description is null or empty, returns an empty string, which causes the section to be skipped in the
     * report.
     *
     * <pre>{@code
     * String content = section.generate();
     * }</pre>
     */
    @Override
    public String generate() {
        if (description == null || description.isEmpty()) {
            return "";  // No description, skip this section
        }

        StringBuilder sb = new StringBuilder();
        sb.append("[Description]\n");
        for (String line : description.split("\n")) {
            sb.append("  ").append(line.trim()).append("\n");
        }
        return sb.toString();
    }

    /**
     * Returns {@code null}.
     *
     * <p>The title is embedded within the content generated by {@link #generate()}.</p>
     */
    @Override
    public String getTitle() {
        return null;  // Title is embedded in content
    }
}
